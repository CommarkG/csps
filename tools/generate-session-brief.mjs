#!/usr/bin/env node
/**
 * generate-session-brief.mjs — machine-generated SESSION-BRIEF.md for humans
 *
 * Reads tools/session-state.json and generates a plain-English summary that the
 * Governor can read in 2 minutes to understand:
 *   - What session just completed
 *   - What the next session should do
 *   - What decisions were made
 *   - What validators must pass before proceeding
 *   - Whether the current session output was correct
 *
 * Run: node tools/generate-session-brief.mjs
 * Output: SESSION-BRIEF.md (root of repo) + committed on session close
 *
 * This IS the human interface to session governance.
 * Per B_MUTUAL_UNDERSTANDING_VALIDATION — every AI communication boundary
 * closes the I→I loop. This document closes the AI→Human loop.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

function getLastCommit() {
  try {
    return execSync('git log --oneline -1', { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch { return 'unknown'; }
}

function getDaysSince(isoDate) {
  if (!isoDate) return '?';
  const days = Math.floor((Date.now() - new Date(isoDate).getTime()) / 86400000);
  return days === 0 ? 'today' : `${days} day(s) ago`;
}

async function main() {
  const statePath = join(ROOT, 'tools/session-state.json');
  if (!existsSync(statePath)) {
    console.error('tools/session-state.json not found');
    process.exit(1);
  }

  const state = JSON.parse(readFileSync(statePath, 'utf8'));
  const lastCommit = getLastCommit();
  const now = new Date().toISOString().split('T')[0];

  const resolvedBlocking = (state.blocking_decisions || [])
    .filter(b => b.status === 'RESOLVED')
    .map(b => `- ✅ **${b.id}**: ${b.decision || 'Resolved'}`)
    .join('\n');

  const pendingBlocking = (state.blocking_decisions || [])
    .filter(b => b.status !== 'RESOLVED')
    .map(b => `- 🔴 **${b.id}**: ${b.question || b.content || 'See tools/session-state.json'}`)
    .join('\n') || '- None — all decisions resolved';

  const startProtocol = (state[`s${state.current_session?.toLowerCase()}_start_protocol`] || state.s013_start_protocol || [])
    .map((s, i) => `${s}`)
    .join('\n');

  const whyBetter = (state.why_better_than_others || [])
    .map(r => `- ${r}`)
    .join('\n');

  const saasArc = Object.entries(state.saas_build_arc || {})
    .map(([key, val]) => {
      const status = val.status === 'COMPLETE' ? `✅ COMPLETE (${val.commit || 'committed'})` :
                     val.status === 'IN_PROGRESS' ? '🔄 IN PROGRESS' : '⏳ PENDING';
      return `| ${key} | ${val.mandate} | ${status} |`;
    })
    .join('\n');

  const brief = `# SESSION BRIEF — ${now}
> **Plain-English status for the Governor.** Read in 2 minutes. No jargon.
> Generated by: \`node tools/generate-session-brief.mjs\`

## Where we are

| Field | Value |
|---|---|
| **Current session** | ${state.current_session || '?'} |
| **Previous session** | ${state.previous_session || '?'} |
| **Last updated** | ${getDaysSince(state.session_updated_at)} |
| **Last commit** | ${lastCommit} |
| **Foundation slices** | ${state.platform_state?.foundation_slices_built ? `✅ BUILT (${state.platform_state.foundation_slices_commit || 'committed'})` : '❌ NOT YET BUILT'} |
| **Apps in production** | ${state.platform_state?.apps_built || 0} |

## What ${state.current_session || 'next session'} must do

**${state.session_mandate?.primary || 'See tools/session-state.json'}**

${startProtocol ? '### Start protocol (copy-paste to start the session)\n\n```\n' + startProtocol + '\n```' : ''}

## Blocking decisions

### ✅ Resolved (already built)
${resolvedBlocking || '- None resolved yet'}

### 🔴 Still pending (decide before proceeding)
${pendingBlocking}

## Platform health

| Metric | Value |
|---|---|
| Validators (pnpm verify) | ${state.platform_state?.pnpm_verify || '?'} |
| Council skills | ${state.platform_state?.skills || '?'} |
| Behavioral contracts | ${state.platform_state?.contracts || '?'} |
| Error patterns (EP) | ${state.platform_state?.ep_patterns || '?'} |
| Moat elements | ${state.platform_state?.moat_elements || '?'} |
| Complexity score | ${state.platform_state?.complexity_score || '?'} (GREEN < 25) |

## SaaS build arc

| Session | Mandate | Status |
|---|---|---|
${saasArc || '| — | See saas_build_arc in tools/session-state.json | — |'}

## Why this builds better than others

${whyBetter || '- See tools/session-state.json for details'}

## How to verify the last session's output

1. Check git log: \`git log --oneline -5\` — does the last commit match the mandate?
2. Run: \`pnpm verify --skip-install\` — must exit 0
3. Check: \`node tools/validators/validate-no-implementation-without-plan.mjs\` — must show \`unplanned=0\`
4. Read: \`tools/session-state.json\` — \`all_blocking_resolved\` must be \`true\`

---
*Auto-generated. Human-readable. Source of truth: tools/session-state.json*
`;

  const outputPath = join(ROOT, 'SESSION-BRIEF.md');
  writeFileSync(outputPath, brief);
  console.log(`[generate-session-brief] Written to SESSION-BRIEF.md`);
}

main().catch(err => { console.error(err); process.exit(1); });
