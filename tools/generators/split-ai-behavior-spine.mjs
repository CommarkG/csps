/**
 * @csps-id csps.generators.split-ai-behavior-spine
 * @csps-description Phase 7 generator — Candidate #4 (token-optimization §9.8 order #4, lowest priority).
 * Reads ai-behavior-spine.md and emits one .md slice per ## section.
 * Run: node tools/generators/split-ai-behavior-spine.mjs  (from repo root)
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const ROOT      = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const SOURCE    = join(ROOT, 'docs/plan/pillar-0-governance/ai-behavior-spine.md');
const SLICES_DIR= join(ROOT, 'docs/plan/pillar-0-governance/ai-behavior-spine');
const INDEX_PATH= join(ROOT, 'docs/plan/pillar-0-governance/ai-behavior-spine-index.yaml');

const content = readFileSync(SOURCE, 'utf8');
const lines   = content.split('\n');

function slugify(name) {
  return name.toLowerCase()
    .replace(/\s*\(.*?\)/g, '').trim()
    .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

const sections = [];
let currentName = null; let currentHeader = null; let currentLines = [];

for (const line of lines) {
  const m = line.match(/^## (.+)$/);
  if (m) {
    if (currentName) sections.push({ name: currentName, slug: slugify(currentName), header: currentHeader, body: currentLines });
    currentName = m[1]; currentHeader = line; currentLines = [];
  } else if (currentName) { currentLines.push(line); }
}
if (currentName) sections.push({ name: currentName, slug: slugify(currentName), header: currentHeader, body: currentLines });

if (sections.length === 0) { console.error('[split-ai-behavior-spine] ERROR: no ## sections found'); process.exit(1); }

if (!existsSync(SLICES_DIR)) mkdirSync(SLICES_DIR, { recursive: true });

const indexEntries = []; let written = 0;

for (const { name, slug, header, body } of sections) {
  const filename = `${slug}.md`;
  const notice = [
    `[//]: # (${filename} — ai-behavior-spine section: ${name})`,
    `[//]: # (Generated by tools/generators/split-ai-behavior-spine.mjs — DO NOT edit directly)`,
    `[//]: # (Source: docs/plan/pillar-0-governance/ai-behavior-spine.md — Phase 7 S010 Candidate #4)`,
    '',
  ].join('\n');
  writeFileSync(join(SLICES_DIR, filename), notice + header + '\n' + body.join('\n').trimEnd() + '\n', 'utf8');
  written++;
  indexEntries.push({ slug, name, path: `./ai-behavior-spine/${filename}` });
}

const today = new Date().toISOString().slice(0, 10);
const idxLines = [
  `# ai-behavior-spine-index.yaml`,
  `# Generated by tools/generators/split-ai-behavior-spine.mjs`,
  `# Source: docs/plan/pillar-0-governance/ai-behavior-spine.md`,
  ``, `meta:`, `  total_count: ${indexEntries.length}`, `  generated_at: '${today}'`,
  `  source: docs/plan/pillar-0-governance/ai-behavior-spine.md`,
  ``, `sections:`,
  ...indexEntries.map(e => `  - slug: ${e.slug}\n    name: "${e.name.replace(/"/g,"'")}"\n    path: ${e.path}`),
  '',
];

writeFileSync(INDEX_PATH, idxLines.join('\n'), 'utf8');
console.log(`[split-ai-behavior-spine] ✓ wrote ${written} slices → ${SLICES_DIR}`);
console.log(`[split-ai-behavior-spine] ✓ wrote index → ${INDEX_PATH}`);
console.log(`[split-ai-behavior-spine] total_count=${indexEntries.length}`);
