/**
 * @csps-id csps.generators.split-audit-runner
 * @csps-description Phase 7 generator — Candidate #3 (token-optimization §9.8 order #3).
 * Reads audit-runner.md and emits one .md slice file per pipeline section at
 * docs/plan/pillar-0-governance/audit-runner/pipeline-<name>.md plus a lightweight index.
 * Monolith preserved as SSoT; slices are generated views for AI context loading.
 * Run: node tools/generators/split-audit-runner.mjs  (from repo root)
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { createHash } from 'node:crypto';

// Windows ESM fix (S014 ZF audit): import.meta.url root resolution fails on Windows
// when run via pnpm script — ESM url path may resolve to desktop instead of repo.
// process.cwd() is the reliable anchor when running from repo root (which pnpm scripts do).
// Drift-log K=1: audit-runner split generator Windows ESM ROOT miscalculation.
const ROOT      = process.cwd();
const SOURCE    = join(ROOT, 'docs/plan/pillar-0-governance/audit-runner.md');
const SLICES_DIR= join(ROOT, 'docs/plan/pillar-0-governance/audit-runner');
const INDEX_PATH= join(ROOT, 'docs/plan/pillar-0-governance/audit-runner-index.yaml');
// CS7: content-hash store — updated here (after split) to indicate audit-runner is current.
// validate-audit-health.mjs CHECK B reads from here instead of mtime comparison.
const VALIDATOR_HASH_STORE = join(ROOT, 'tools/data/validator-content-hashes.json');

const content = readFileSync(SOURCE, 'utf8');
const lines   = content.split(/\r?\n/);  // handle both LF and CRLF (Windows fix S014)

// ── Parse pipeline sections (### headers) ─────────────────────────────────────

function slugify(name) {
  return name.toLowerCase()
    .replace(/\s*\(.*?\)/g, '')   // remove (N) count
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

const sections = [];
let currentName = null;
let currentHeader = null;
let currentLines = [];

for (const line of lines) {
  const m = line.match(/^### (.+)$/);
  if (m) {
    if (currentName) {
      sections.push({ name: currentName, slug: slugify(currentName), header: currentHeader, body: currentLines });
    }
    currentName   = m[1];
    currentHeader = line;
    currentLines  = [];
  } else if (currentName) {
    currentLines.push(line);
  }
}
if (currentName) sections.push({ name: currentName, slug: slugify(currentName), header: currentHeader, body: currentLines });

if (sections.length === 0) {
  console.error('[split-audit-runner] ERROR: no ### pipeline sections found');
  process.exit(1);
}

// ── Ensure output dir ──────────────────────────────────────────────────────────

if (!existsSync(SLICES_DIR)) mkdirSync(SLICES_DIR, { recursive: true });

// ── Emit slices ────────────────────────────────────────────────────────────────

const indexEntries = [];
let written = 0;

for (const { name, slug, header, body } of sections) {
  const filename = `pipeline-${slug}.md`;
  const filePath = join(SLICES_DIR, filename);

  const notice = [
    `[//]: # (pipeline-${slug}.md — audit-runner pipeline: ${name})`,
    `[//]: # (Generated by tools/generators/split-audit-runner.mjs — DO NOT edit directly)`,
    `[//]: # (Source: docs/plan/pillar-0-governance/audit-runner.md — Phase 7 S010)`,
    '',
  ].join('\n');

  writeFileSync(filePath, notice + header + '\n' + body.join('\n').trimEnd() + '\n', 'utf8');
  written++;
  indexEntries.push({ slug: `pipeline-${slug}`, name, path: `./audit-runner/pipeline-${slug}.md` });
}

// ── Emit index ─────────────────────────────────────────────────────────────────

const today = new Date().toISOString().slice(0, 10);
const idxLines = [
  `# audit-runner-index.yaml`,
  `# CSPS Audit Runner Index — generated by tools/generators/split-audit-runner.mjs`,
  `# Source: docs/plan/pillar-0-governance/audit-runner.md`,
  `# Run \`node tools/generators/split-audit-runner.mjs\` to regenerate`,
  ``,
  `meta:`,
  `  total_count: ${indexEntries.length}`,
  `  generated_at: '${today}'`,
  `  source: docs/plan/pillar-0-governance/audit-runner.md`,
  `  slices_dir: docs/plan/pillar-0-governance/audit-runner/`,
  ``,
  `pipelines:`,
  ...indexEntries.map(e => `  - slug: ${e.slug}\n    name: "${e.name.replace(/"/g,"'")}"\n    path: ${e.path}`),
  '',
];

writeFileSync(INDEX_PATH, idxLines.join('\n'), 'utf8');

console.log(`[split-audit-runner] ✓ wrote ${written} pipeline slices → ${SLICES_DIR}`);
console.log(`[split-audit-runner] ✓ wrote index → ${INDEX_PATH}`);
console.log(`[split-audit-runner] total_count=${indexEntries.length}`);

// CS7: update content-hash store for all validators.
// Called after audit-runner.md is confirmed current (split = audit is fresh).
// validate-audit-health.mjs CHECK B uses this instead of mtime comparison.
try {
  const validatorsDir = join(ROOT, 'tools/validators');
  const validatorFiles = readdirSync(validatorsDir)
    .filter(f => f.startsWith('validate-') && f.endsWith('.mjs'));

  const hashes = {};
  for (const vf of validatorFiles) {
    const vpath = join(validatorsDir, vf);
    // Hash the first 500 chars — captures @csps-id, @csps-version, description block.
    // This is the "signature" that should change when the validator logic changes.
    const content = readFileSync(vpath, 'utf8').slice(0, 500);
    hashes[vf] = createHash('sha256').update(content).digest('hex').slice(0, 16);
  }

  writeFileSync(VALIDATOR_HASH_STORE, JSON.stringify({
    _comment: 'CS7: validator content-hash store. Updated by pnpm audit-runner:split. Read by validate-audit-health.mjs CHECK B. Stale = current hash != stored hash (not mtime). B_DETERMINISTIC_GATE compliant.',
    _updated_at_split: new Date().toISOString().slice(0, 10),
    hashes,
  }, null, 2), 'utf8');
  console.log(`[split-audit-runner] ✓ wrote validator hashes → tools/data/validator-content-hashes.json (${validatorFiles.length} validators)`);
} catch (e) {
  console.warn(`[split-audit-runner] ⚠ could not write validator hashes: ${e.message}`);
}
