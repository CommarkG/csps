/**
 * @csps-id csps.generators.split-behavioral-contracts
 * @csps-description Phase 7 generator — Candidate #2 (token-optimization §9.8 order #2).
 * Reads behavioral-contracts.md and emits one .md slice file per B_* contract at
 * docs/plan/pillar-0-governance/behavioral-contracts/B_NAME.md plus a lightweight
 * behavioral-contracts-index.yaml manifest.
 * Monolith is preserved as the canonical SSoT; slices are generated views for AI session
 * context loading (~48K monolith → 1-3K per-contract slice).
 * Run: node tools/generators/split-behavioral-contracts.mjs  (from repo root)
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT      = resolve(__dirname, '../..');

const SOURCE     = join(ROOT, 'docs/plan/pillar-0-governance/behavioral-contracts.md');
const SLICES_DIR = join(ROOT, 'docs/plan/pillar-0-governance/behavioral-contracts');
const INDEX_PATH = join(ROOT, 'docs/plan/pillar-0-governance/behavioral-contracts-index.yaml');

// ── Read source ────────────────────────────────────────────────────────────────

const content = readFileSync(SOURCE, 'utf8');
const lines   = content.split('\n');

// ── Parse sections ─────────────────────────────────────────────────────────────
// Split by "## B_" headers.  Everything before the first match = preamble (ignored in slices).

const sections = [];
let currentName    = null;
let currentHeader  = null;
let currentBody    = [];

for (const line of lines) {
  // Match canonical B_* section header (## B_NAME or ## B_NAME — ...)
  const m = line.match(/^## (B_[A-Z0-9_]+)/);
  if (m) {
    if (currentName) {
      sections.push({ name: currentName, header: currentHeader, body: currentBody });
    }
    currentName   = m[1];
    currentHeader = line;
    currentBody   = [];
  } else if (currentName) {
    currentBody.push(line);
  }
}
// Flush last section
if (currentName) {
  sections.push({ name: currentName, header: currentHeader, body: currentBody });
}

if (sections.length === 0) {
  console.error('[split-behavioral-contracts] ERROR: no B_* sections found in behavioral-contracts.md');
  process.exit(1);
}

// ── Ensure output dir ──────────────────────────────────────────────────────────

if (!existsSync(SLICES_DIR)) mkdirSync(SLICES_DIR, { recursive: true });

// ── Emit slice files ───────────────────────────────────────────────────────────

const indexEntries = [];
let written = 0;

for (const { name, header, body } of sections) {
  const filename = `${name}.md`;
  const filePath = join(SLICES_DIR, filename);
  const relPath  = `./behavioral-contracts/${filename}`;

  // Strip trailing blank lines from body
  const trimmedBody = body.join('\n').trimEnd();

  // Generation notice (Markdown comment — renders as nothing in viewers)
  const notice = [
    `[//]: # (${name}.md)`,
    `[//]: # (CSPS Behavioral Contract Slice — generated by tools/generators/split-behavioral-contracts.mjs)`,
    `[//]: # (Source of truth: docs/plan/pillar-0-governance/behavioral-contracts.md)`,
    `[//]: # (DO NOT edit — run \`node tools/generators/split-behavioral-contracts.mjs\` to regenerate)`,
    `[//]: # (Phase 7 token-optimization §9.8 Candidate #2 S010 — load ${filename} instead of full ~48K monolith)`,
    '',
  ].join('\n');

  const sliceContent = notice + header + '\n' + trimmedBody + '\n';
  writeFileSync(filePath, sliceContent, 'utf8');
  written++;

  // Derive a short description from the header line
  const descMatch = header.match(/^##\s+B_[A-Z0-9_]+\s*[—-]\s*(.+)$/);
  const desc = descMatch ? descMatch[1].trim().split('(')[0].trim().slice(0, 80) : name;

  indexEntries.push({ name, desc, path: relPath });
}

// ── Emit YAML index (pure string; no js-yaml dependency) ──────────────────────

const today = new Date().toISOString().slice(0, 10);
const indexLines = [
  `# behavioral-contracts-index.yaml`,
  `# CSPS Behavioral Contracts Index — generated by tools/generators/split-behavioral-contracts.mjs`,
  `# Lightweight manifest: use this to find which slice file to load`,
  `# instead of loading the full ~48K behavioral-contracts.md.`,
  `# Source: docs/plan/pillar-0-governance/behavioral-contracts.md`,
  `# Run \`node tools/generators/split-behavioral-contracts.mjs\` to regenerate`,
  ``,
  `meta:`,
  `  total_count: ${indexEntries.length}`,
  `  generated_at: '${today}'`,
  `  source: docs/plan/pillar-0-governance/behavioral-contracts.md`,
  `  slices_dir: docs/plan/pillar-0-governance/behavioral-contracts/`,
  `  usage: Load individual slice files (./behavioral-contracts/B_NAME.md) for AI session context;`,
  `         load this index to discover available contracts without loading full monolith`,
  ``,
  `contracts:`,
  ...indexEntries.map(e => [
    `  - id: ${e.name}`,
    `    desc: "${e.desc.replace(/"/g, "'")}"`,
    `    path: ${e.path}`,
  ].join('\n')),
  '',
];

writeFileSync(INDEX_PATH, indexLines.join('\n'), 'utf8');

console.log(`[split-behavioral-contracts] ✓ wrote ${written} slice files → ${SLICES_DIR}`);
console.log(`[split-behavioral-contracts] ✓ wrote index → ${INDEX_PATH}`);
console.log(`[split-behavioral-contracts] total_count=${indexEntries.length}`);
