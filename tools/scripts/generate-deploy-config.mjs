#!/usr/bin/env node
/**
 * @csps-id csps.tools.scripts.generate-deploy-config
 * @csps-name generate-deploy-config
 * @csps-description FLAWLESS-DEPLOY M3 — generator. Given an app name, emits:
 *   (1) apps/[app]/vercel.json — canonical vercel.json per vercel.md spec (R2+R3: framework:nextjs, no _comment)
 *   (2) apps/[app]/.csps/deploy-checklist.md — 7-step Vercel UI sequence
 *   (3) Appends entry to tools/config/deploy-targets.yaml
 * Usage: node tools/scripts/generate-deploy-config.mjs --app [appname]
 * @csps-version 1.0.0
 * @csps-owner group:finky
 * @csps-lifecycle production
 * @csps-lifecycle-state active
 * @csps-enforces P-ARCH-030 B_APPS_ARE_TRIALS
 */

import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join } from 'path';

const ROOT = process.cwd();
const args = process.argv.slice(2);
const appIdx = args.indexOf('--app');
const appName = appIdx >= 0 ? args[appIdx + 1] : null;

if (!appName) {
  console.error('Usage: node tools/scripts/generate-deploy-config.mjs --app [appname]');
  process.exit(1);
}

if (!/^[a-z][a-z0-9-]+$/.test(appName)) {
  console.error(`Invalid app name: "${appName}" — use lowercase letters, numbers, hyphens only`);
  process.exit(1);
}

const appPath = join(ROOT, 'apps', appName);
if (!existsSync(appPath)) {
  console.error(`apps/${appName}/ does not exist — create the app first, then run this generator`);
  process.exit(1);
}

console.log(`[generate-deploy-config] Generating deploy config for: ${appName}`);

// ── 1. vercel.json ──────────────────────────────────────────────────────────
const vercelJsonPath = join(appPath, 'vercel.json');
if (existsSync(vercelJsonPath)) {
  console.log(`  ⚠  vercel.json already exists — skipping (ADD-not-REPLACE)`);
} else {
  const vercelJson = {
    framework: 'nextjs',
    env: {
      NEXT_PUBLIC_CLERK_SIGN_IN_URL: '/sign-in',
      NEXT_PUBLIC_CLERK_SIGN_UP_URL: '/sign-up',
      NEXT_PUBLIC_CLERK_AFTER_SIGN_IN_URL: '/dashboard',
      NEXT_PUBLIC_CLERK_AFTER_SIGN_UP_URL: '/dashboard',
    },
    regions: ['iad1'],
  };
  writeFileSync(vercelJsonPath, JSON.stringify(vercelJson, null, 2) + '\n');
  console.log(`  ✓ Created apps/${appName}/vercel.json`);
}

// ── 2. deploy-checklist.md ──────────────────────────────────────────────────
const checklistDir = join(appPath, '.csps');
const checklistPath = join(checklistDir, 'deploy-checklist.md');
if (!existsSync(checklistDir)) mkdirSync(checklistDir, { recursive: true });

if (existsSync(checklistPath)) {
  console.log(`  ⚠  deploy-checklist.md already exists — skipping`);
} else {
  const checklist = `# Deploy Checklist — ${appName}
## Vercel UI: 7-Step Sequence (from vercel.md R1-R10)

Run these ONCE when creating the Vercel project. After first successful deploy, update status:deployed in tools/config/deploy-targets.yaml.

### Step 1 — Create project
- [ ] Go to vercel.com → New Project → Import Git Repository: CommarkG/csps

### Step 2 — Root Directory
- [ ] Set Root Directory: \`apps/${appName}\`
- [ ] ✓ This is the most critical setting. Wrong value = silent 404s on all routes (budget-planner failure class).

### Step 3 — Framework Preset
- [ ] Framework Preset: Next.js (auto-detected from vercel.json)

### Step 4 — Build Command
- [ ] Build Command: \`pnpm --filter ${appName} build\`

### Step 5 — Include files outside root
- [ ] Settings → General → Build & Deployment → Include Files Outside Root: **Enabled**
- [ ] Required for access to libs/, packages/ from pnpm workspace

### Step 6 — Environment Variables
Add these in Vercel UI (Project Settings → Environment Variables):
- [ ] DATABASE_URL (Supabase port 6543 + ?pgbouncer=true&connection_limit=1)
- [ ] DIRECT_URL (Supabase port 5432)
- [ ] NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY
- [ ] CLERK_SECRET_KEY
- [ ] Any app-specific vars from apps/${appName}/.env.example

### Step 7 — First Deploy
- [ ] Click Deploy
- [ ] Verify: all routes return 200 (not 404)
- [ ] Update tools/config/deploy-targets.yaml: status: active → deployed + deploy_url

---
*Generated by tools/scripts/generate-deploy-config.mjs | See vercel.md for full rules*
`;
  writeFileSync(checklistPath, checklist);
  console.log(`  ✓ Created apps/${appName}/.csps/deploy-checklist.md`);
}

// ── 3. Append to deploy-targets.yaml ───────────────────────────────────────
const targetsPath = join(ROOT, 'tools/config/deploy-targets.yaml');
if (existsSync(targetsPath)) {
  const existing = readFileSync(targetsPath, 'utf-8');
  if (existing.includes(`- app: ${appName}`)) {
    console.log(`  ⚠  deploy-targets.yaml already has entry for ${appName} — skipping`);
  } else {
    // Find the insertion point: before the status enum comment at the end
    const insertBefore = '\n# --- Status enum ---';
    const newEntry = `
  - app: ${appName}
    root_dir: apps/${appName}
    framework: nextjs
    vercel_project: csps-${appName}
    status: active
    deploy_url: null
    note: "Generated by generate-deploy-config.mjs"
    closure_owner: group:finky
    closure_decision: "First production deploy verified — set status:deployed + deploy_url"
    closure_by: "before this app goes to production"
`;
    const updated = existing.includes(insertBefore)
      ? existing.replace(insertBefore, newEntry + insertBefore)
      : existing + newEntry;
    writeFileSync(targetsPath, updated);
    console.log(`  ✓ Added entry to tools/config/deploy-targets.yaml`);
  }
}

console.log(`\n[generate-deploy-config] Done. Next steps:
  1. node tools/scripts/deploy-check.mjs  (verify config is valid)
  2. Follow apps/${appName}/.csps/deploy-checklist.md in Vercel UI
  3. After first deploy: update deploy-targets.yaml status: deployed + deploy_url`);
