/**
 * @csps-id csps.tools.scripts.session-open-floater-inject
 * @csps-name session-open-floater-inject
 * @csps-description ANTI-FLOAT T3 — session-open injection of overdue floaters.
 *   Called by session-open.sh at every tab start. Reads floating-artifacts-register.yaml,
 *   surfaces overdue items to the AI in context, and writes .csps/floater-decision-queue.txt
 *   for Governor decision-making.
 *   Per P-META-030 enforcement_tier.tier3_session: "session-open injection of overdue floaters (B4 M3)".
 *   This IS the T3 layer for ANTI-FLOAT (T1=pre-tool-use-closure-obligation-required.sh;
 *   T2=validate-no-floating-artifacts.mjs; T3=this script + close-gate-floater-check.mjs).
 * @csps-version 1.0.0
 * @csps-owner group:finky
 * @csps-lifecycle production
 * @csps-lifecycle-state active
 * @csps-tags type:script domain:governance audience:ai-agent
 * @csps-enforces P-META-030 B_ANTI_FLOAT
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const ROOT = process.env.CSPS_REPO_ROOT || process.cwd();

// ── Load floating-artifacts-register.yaml ────────────────────────────────────
const REGISTER_PATH = join(ROOT, 'tools/data/floating-artifacts-register.yaml');
const QUEUE_PATH = join(ROOT, '.csps/floater-decision-queue.txt');
const QUEUE_DIR = join(ROOT, '.csps');

let entries = [];
try {
  const raw = readFileSync(REGISTER_PATH, 'utf8');
  const reg = yaml.load(raw);
  entries = reg.entries || [];
} catch (e) {
  process.stderr.write('\n[ANTI-FLOAT-T3] ⚠ Could not read floating-artifacts-register.yaml: ' + e.message);
  process.exit(0);
}

// ── Classify entries ─────────────────────────────────────────────────────────
const overdue = entries.filter(e => e.escalation_state === 'overdue');
const terminal = entries.filter(e => e.escalation_state === 'terminal');
const total = entries.length;

// ── Stderr injection (always fires — low-noise format) ───────────────────────
if (overdue.length === 0) {
  process.stderr.write('\n[ANTI-FLOAT-T3] ✅ No overdue floaters. Total tracked: ' + total + ' (' + terminal.length + ' terminal).');
} else {
  process.stderr.write(
    '\n[ANTI-FLOAT-T3] ⚠ FLOATER BACKLOG: ' + overdue.length + ' overdue / ' + total + ' total. ' +
    'EVERY SESSION: pick ≥1 item → terminal decision. Full list: .csps/floater-decision-queue.txt'
  );

  // Show top 5 oldest (earliest sessions first)
  const sorted = [...overdue].sort((a, b) => {
    const sa = (a.created_session || 'S099').replace('S', '');
    const sb = (b.created_session || 'S099').replace('S', '');
    return parseInt(sa) - parseInt(sb);
  });

  sorted.slice(0, 5).forEach(e => {
    const sessLabel = e.created_session || 'S???';
    const shortDecision = (e.closure_decision || 'see register').substring(0, 80);
    process.stderr.write('\n  → [' + sessLabel + '] ' + e.id + ': ' + shortDecision);
  });

  if (overdue.length > 5) {
    process.stderr.write('\n  ... +' + (overdue.length - 5) + ' more in .csps/floater-decision-queue.txt');
  }
}

// ── Write .csps/floater-decision-queue.txt ───────────────────────────────────
try {
  if (!existsSync(QUEUE_DIR)) mkdirSync(QUEUE_DIR, { recursive: true });

  const lines = [
    '# FLOATER DECISION QUEUE',
    '# Auto-generated by session-open-floater-inject.mjs at ' + new Date().toISOString(),
    '# Per P-META-030 + ANTI-FLOAT T3. Each item needs a TERMINAL decision.',
    '# Decisions: SUPERSEDED | RATIFIED | ARCHIVED | REJECTED | CARRY-FORWARD-with-trigger',
    '# Process: read item → make decision → update floating-artifacts-register.yaml entry',
    '#   set escalation_state: terminal AND terminal_state: <decision>',
    '',
    '## STATS',
    '# Total tracked: ' + total,
    '# Overdue: ' + overdue.length,
    '# Terminal: ' + terminal.length,
    '',
    '## OVERDUE ITEMS (oldest first)',
    '',
  ];

  if (overdue.length === 0) {
    lines.push('(none — all items have terminal states)');
  } else {
    const sorted = [...overdue].sort((a, b) => {
      const sa = (a.created_session || 'S099').replace('S', '');
      const sb = (b.created_session || 'S099').replace('S', '');
      return parseInt(sa) - parseInt(sb);
    });

    sorted.forEach((e, i) => {
      lines.push('---');
      lines.push('[ ] ' + (i + 1) + '. ' + e.id + ' [session: ' + (e.created_session || '?') + ']');
      lines.push('    artifact: ' + (e.artifact_path || 'unknown'));
      lines.push('    closure_owner: ' + (e.closure_owner || 'unset'));
      lines.push('    decision_needed: ' + (e.closure_decision || 'unset'));
      if (e.note) lines.push('    note: ' + e.note.substring(0, 120));
      lines.push('');
    });
  }

  writeFileSync(QUEUE_PATH, lines.join('\n'), 'utf8');
} catch (e) {
  process.stderr.write('\n[ANTI-FLOAT-T3] ⚠ Could not write decision queue: ' + e.message);
}

process.exit(0);
